export const radarRoots: Record<RadarLocale, string> = {
  fr: '/fr/us/radar-latino/',
  en: '/en/us/latino-radar/',
  es: '/es/us/radar-latino/',
};

/** Lien exact vers la projection de la course, dans la langue de la fiche. */
const PROJECTION_ROOTS = {
  house: { fr: '/fr/us/chambre/districts/', en: '/en/us/house/districts/', es: '/es/us/house/distritos/' },
  senate: { fr: '/fr/us/senat/sieges/', en: '/en/us/senate/seats/', es: '/es/us/senate/escanos/' },
} as const;
export function raceProjectionUrl(race: { office: string; riding_id: string; name: string }, slug: string | undefined, locale: RadarLocale): string | null {
  const roots = PROJECTION_ROOTS[race.office as 'house' | 'senate'];
  return roots && slug ? `${roots[locale]}${slug}/` : null;
}

export function partyLabel(party: string, locale: RadarLocale) {
  const labels: Record<string, Record<RadarLocale, string>> = {
    us_dem: { fr: 'Dém.', en: 'Dem.', es: 'Dem.' },
    us_rep: { fr: 'Rép.', en: 'Rep.', es: 'Rep.' },
    us_oth: { fr: 'Autre', en: 'Other', es: 'Otro' },
  };
  return labels[party]?.[locale] ?? party;
}
